#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
MINERVA_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

export LIVESQLBENCH_MODEL="${LIVESQLBENCH_MODEL:?Set LIVESQLBENCH_MODEL}"
export LIVESQLBENCH_RUN_NAME="${LIVESQLBENCH_RUN_NAME:?Set LIVESQLBENCH_RUN_NAME}"
export LIVESQLBENCH_RUNS_DIR="${LIVESQLBENCH_RUNS_DIR:-$SCRIPT_DIR/runs}"
export LIVESQLBENCH_RUN_DIR="${LIVESQLBENCH_RUN_DIR:-$LIVESQLBENCH_RUNS_DIR/$LIVESQLBENCH_RUN_NAME}"
export LIVESQLBENCH_DATASET_JSONL="${LIVESQLBENCH_DATASET_JSONL:-$SCRIPT_DIR/artifacts/livesqlbench_base_full_v1_full.jsonl}"
export LIVESQLBENCH_DATASET_ROOT="${LIVESQLBENCH_DATASET_ROOT:-$MINERVA_ROOT/sql-benchmark/livesqlbench-base-full-v1}"
export LIVESQLBENCH_LIMIT="${LIVESQLBENCH_LIMIT:-}"
export LIVESQLBENCH_N="${LIVESQLBENCH_N:-8}"
export LIVESQLBENCH_TEMPERATURE="${LIVESQLBENCH_TEMPERATURE:-0.8}"
export LIVESQLBENCH_TOP_P="${LIVESQLBENCH_TOP_P:-0.95}"
export LIVESQLBENCH_TP="${LIVESQLBENCH_TP:-1}"
export LIVESQLBENCH_MAX_TOKENS="${LIVESQLBENCH_MAX_TOKENS:-768}"
export LIVESQLBENCH_MAX_MODEL_LEN="${LIVESQLBENCH_MAX_MODEL_LEN:-16384}"
export LIVESQLBENCH_GPU_UTIL="${LIVESQLBENCH_GPU_UTIL:-0.9}"
export LIVESQLBENCH_BACKEND="${LIVESQLBENCH_BACKEND:-vllm}"
export LIVESQLBENCH_PG_HOST="${LIVESQLBENCH_PG_HOST:-127.0.0.1}"
export LIVESQLBENCH_PG_PORT="${LIVESQLBENCH_PG_PORT:-15432}"
export VLLM_WORKER_MULTIPROC_METHOD="${VLLM_WORKER_MULTIPROC_METHOD:-spawn}"
export TRANSFORMERS_NO_TF="${TRANSFORMERS_NO_TF:-1}"

mkdir -p "$LIVESQLBENCH_RUN_DIR"
PRED_JSONL="$LIVESQLBENCH_RUN_DIR/predictions.jsonl"

GEN_CMD=(
  python "$SCRIPT_DIR/generate_sql_predictions.py"
  --model "$LIVESQLBENCH_MODEL"
  --output-jsonl "$PRED_JSONL"
  --dataset-jsonl "$LIVESQLBENCH_DATASET_JSONL"
  --dataset-root "$LIVESQLBENCH_DATASET_ROOT"
  --tensor-parallel-size "$LIVESQLBENCH_TP"
  --temperature "$LIVESQLBENCH_TEMPERATURE"
  --top-p "$LIVESQLBENCH_TOP_P"
  --n "$LIVESQLBENCH_N"
  --max-tokens "$LIVESQLBENCH_MAX_TOKENS"
  --max-model-len "$LIVESQLBENCH_MAX_MODEL_LEN"
  --gpu-memory-utilization "$LIVESQLBENCH_GPU_UTIL"
  --backend "$LIVESQLBENCH_BACKEND"
  --trust-remote-code
)

if [ -n "$LIVESQLBENCH_LIMIT" ]; then
  GEN_CMD+=(--limit "$LIVESQLBENCH_LIMIT")
fi

"${GEN_CMD[@]}"

LIVESQLBENCH_JSONL_FILE="$PRED_JSONL" \
LIVESQLBENCH_EVAL_OUTPUT_DIR="$LIVESQLBENCH_RUN_DIR" \
LIVESQLBENCH_PG_HOST="$LIVESQLBENCH_PG_HOST" \
LIVESQLBENCH_PG_PORT="$LIVESQLBENCH_PG_PORT" \
bash "$SCRIPT_DIR/evaluate_predictions.sh"
